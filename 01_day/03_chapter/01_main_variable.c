// 变量:就是一个容器,用来存储数据,也可以修改数据
// 变量需要先声明,后赋值,才可以使用
// 变量的声明或定义的语法:
// 方式1:先声明后赋值,语法:
// 数据类型名 变量名;
// 变量名 = 值;
// 方式2:声明的同时直接赋值,语法:
// 数据类型名 变量名 = 值;
// 方式3:同时声明多个变量并赋值,语法:
// 数据类型名 变量名1=值1,变量名2=值2,变量名3=值3;

#include <stdio.h>

int main()
{
  // 声明变量的方式1:
  // 声明了一个变量,起名为num1,是int类型的
  int num1;
  // 为变量num1赋值为10
  num1 = 10;
  // 通过printf输出语句打印num1变量的值,%d----格式占位符,用来展示num1变量的值的
  printf("num1的值是:%d\n", num1);

  // 声明变量的方式2:
  // 声明了一个int类型的变量,起名为num2,并赋值为20
  int num2 = 20;
  printf("num2的值是:%d\n",num2);

  // 声明变量的方式3:
  // 一次性声明多个int类型的变量,起名为x,y,z并分别赋值为10,20,30
  int x = 10, y = 20, z = 30;
  printf("x=%d,y=%d,z=%d\n",x,y,z);

  return 0;
}