  /*

    if-else语句语法:

    if(条件表达式){
      语句1/代码块1;
    }else{
      语句2/代码块2;
    }
    语句/代码块:指的是一行或多行代码
    条件表达式:是布尔类型值

    if-else语句的执行过程:代码执行到if(条件表达式)这一行,先判断表达式的值是否为真(真----1---true/假---0----false)
    如果为真,则执行语句1,执行完毕后跳过大括号向后执行
    如果为假,则执行语句2,执行完毕后跳过大括号向后执行


    if-else语句简化写法:如果大括号中的代码只有一行,则大括号可以省略,注意缩进


  */
