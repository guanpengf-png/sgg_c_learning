  /*

    while循环语法:
    while(条件表达式){
      循环体语句;/循环体语句代码;/代码块;
    }





    条件表达式:其计算结果是布尔类型值
    循环体语句:可以是一行代码,也可以是多行代码


    while循环的执行过程:代码执行到while(条件表达式)这一行的时候,计算该表达式的结果是否为真(真----1----true/假----0---false)
    如果为真,则执行大括号中循环体语句代码,然后再次执行到条件表达式这个位置,计算表达式的值是否为真
    如果为真,则执行大括号中循环体语句代码,然后再次执行到条件表达式这个位置,计算表达式的值是否为真
    如果为真,则执行大括号中循环体语句代码,然后再次执行到条件表达式这个位置,计算表达式的值是否为真
    直到表达式为假
    如果为假,则结束循环

    while循环语法例子:
      int i = 0;  计数器
      while(i<5){
        循环体语句;
        i++;
     }

     先执行int i=0;叫初始化计数器,默认值为0
     然后执行到while(i<5)这一行,判断i<5是否成立(真---1---true/假----0---false),
     如果为假,则循环体语句代码(大括号中的代码)不执行,就结束了
     如果为真,则执行循环体语句代码,然后执行i++,然后再次回到i<5的位置进行计算
     判断i<5是否为真
     ......
      如果为假,则循环体语句代码(大括号中的代码)不执行,就结束了
     如果为真,则执行循环体语句代码,然后执行i++,然后再次回到i<5的位置进行计算
     判断i<5是否为真


     如果一个循环语句中的条件是恒成立的,或者说没有结束条件,就是一个无限循环(死循环)


  */

