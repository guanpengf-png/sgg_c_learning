#include <stdio.h>
int main()
{
  // 分支语句之单向分支:if语句
  /*

    if语句:

    if语句语法:
    if(表达式){
      语句/代码块;
    }
    表达式:其结果是布尔类型的值
    语句/代码块:一行或多行代码

    if语句的执行过程:首先代码执行到if(表达式)这一行的时候,先判断表达式的结果是否为真(真---1---true,假---0---false)
    如果为假,则跳过大括号中语句向后执行
    如果为真,则执行大括号中的语句代码,然后再进行向后执行

    if语句的简化写法:如果大括号中的代码只有一行,则大括号可以省略,但是要注意缩进


  */

  // 例子:根据用户输入的年龄,成年,则提示可以看电影了
  int age = 0; // 用来存储年龄数据的变量
  printf("请您输入年龄:\n");
  scanf("%d", &age); // 接收数据
  if (age >= 18)
    printf("可以看电影了,嘿嘿\n");
  printf("程序结束\n");

  return 0;
}