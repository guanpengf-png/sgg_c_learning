#include <stdio.h>
int main()
{
  // 分支语句之多向分支语句:
  // if-else if-else if-else if...语句
  // if-else if-else if....else语句

  /*

    if-else if语句的语法:
    if(表达式1){
      语句1/代码块1;
    }else if(表达式2){
      语句2/代码块2;
    }else if(表达式3){
      语句3/代码块3;
    }...
    else{
      语句4/代码块4;
    }

    if-else if语句的执行过程:
    代码执行到if(表达式1)的时候,判断表达式的结果是否成立/为真(真----1---true/假---0---false)
    如果为真,则执行语句1,然后结束,可以继续向后执行
    如果为假,则判断表达式2是否为真,如果为真,则执行语句2,然后结束,可以继续向后执行
    如果为假,则判断表达式3是否为真,如果为真,则执行语句3,然后结束,可以继续向后执行
    如果为假,则要看else是否存在,存在则执行else大括号中的代码,没有则继续向后执行


    if-else if语句的执行简化:
    如果大括号中的代码只有一行,则大括号也可以省略,注意缩进



  */
  // 例子:输入小甜甜的成绩,如果分数在90(含)以上,则奖励一个包子
  // 如果成绩在80(含)到90之间,则奖励一个花卷
  // 如果成绩在60(含)到80之间,则奖励一个馒头
  // 如果成绩在60以下,则奖励一个你真棒

  int score = 92; // 分数
  if (score >= 90 && score <= 100)
    printf("奖励一个包子\n");
  else if (score >= 80)
    printf("奖励一个花卷\n");
  else if (score >= 60)
    printf("奖励一个馒头\n");
  else
    printf("你真棒,继续加油\n");
  printf("程序结束\n");
  return 0;
}