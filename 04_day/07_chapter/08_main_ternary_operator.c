#include <stdio.h>
int main()
{
  // 三元运算符   ?:
  // 三元运算表达式:由三元运算符连接起来的式子
  // 三元运算表达式的语法: 表达式1?表达式2:表达式3;
  // 三元运算表达式的结果:要么是表达式2的结果,要么是表达式3的结果
  // 三元运算表达式的计算过程:先判断表达式1是否成立(是否为真,真---1---true/假---0---false),如果成立,则计算表达式2的结果,否则计算表达式3的结果

  // 例子:求两个整数的最大值
  int a = 0, b = 0;
  printf("请您输入两个整数:\n");
  scanf("%d %d", &a, &b);
  int max_number = a > b ? a : b;
  printf("结果:%d\n", max_number);
  printf("\n=================\n");
  // 例子:求三个整数的最大值
  int x = 100, y = 300, z = 50;
  // 嵌套的三元表达式
  int max_number2 = x > y ? (x > z ? x : z) : (y > z ? y : z);
  printf("结果是:%d\n",max_number2);

  return 0;
}