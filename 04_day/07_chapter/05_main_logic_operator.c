#include <stdio.h>
int main()
{
  // 逻辑运算符: &&--逻辑与运算符(并且)   ||----逻辑或运算符(或者)   !----逻辑非(取非)
  // 逻辑运算表达式:由逻辑运算符连接起来的式子
  // 逻辑运算表达式的结果:布尔类型值
  {
    // &&----逻辑与/并且
    // 逻辑与表达式:表达式1&&表达式2
    // 逻辑与的运算过程:如果表达式1和表达式2都为真,则整个结果为真,否则为假
    // 逻辑与短路:如果第一个表达式为假,则第二个表达式不再计算
    int a = 10, b = 7;
    printf("逻辑与运算符 && 对应的表达式: a+5>b&&b+3>2的结果:%d\n", a + 5 > b && b + 3 > 2); // 1
    printf("逻辑与运算符 && 对应的表达式: a+5>b&&b+3<2的结果:%d\n", a + 5 > b && b + 3 < 2); // 0
    // 逻辑与短路
    printf("逻辑与运算符 && 对应的表达式: a+5<b&&b++的结果:%d,b=%d\n", a + 5 < b && b++, b); // 0 7
  }
  printf("\n===============\n");
  {
    // ||----逻辑或/或者
    // 逻辑或表达式:表达式1||表达式2
    // 逻辑或的运算过程:如果表达式1和表达式2都为假,则整个结果为假,否则为真
    // 逻辑或短路:如果第一个表达式为真,则第二个表达式不再计算
    int a = 10, b = 7;
    printf("逻辑或运算符 || 应的表达式: a+5<b||b+3<2的结果:%d\n", a + 5 < b || b + 3 < 2); // 0
    printf("逻辑或运算符 || 应的表达式: a+5>b||b+3<2的结果:%d\n", a + 5 > b || b + 3 < 2); // 1
    // 逻辑与短路
    printf("逻辑或运算符 || 应的表达式: a+5>b||b++的结果:%d,b=%d\n", a + 5 > b || b++, b); // 1 7
  }
  printf("\n===============\n");

  {
    // !---逻辑非
    // 逻辑非表达式:!表达式
    // 逻辑非运算过程:真为假,假为真
    int a = 10;
    printf("逻辑非运算符 ! 对应的表达式: !(a+3>5) 的结果是:%d\n", !(a + 3 > 5));
  }
  return 0;
}