#include <stdio.h>
int main()
{
  // 关系运算符(比较运算符): >大于 <小于 >=大于等于 <=小于等于 == 相等 != 不等
  // 关系运算表达式:由关系运算符连接起来的式子叫关系运算表达式
  // 关系运算表达式的结果:是布尔类型值
  {
    // >大于 <小于 >=大于等于 <=小于等于 == 相等 != 不等
    printf("关系运算符 > 大于运算符 对应的表达式:10>3的结果:%d\n", 10 > 3);        // 1
    printf("关系运算符 >= 大于等于运算符 对应的表达式:10>=3的结果:%d\n", 10 >= 3); // 1
    printf("关系运算符 < 小于运算符 对应的表达式:10<3的结果:%d\n", 10 < 3);        // 0
    printf("关系运算符 <= 小于等于运算符 对应的表达式:10<=3的结果:%d\n", 10 <= 3); // 0
    printf("关系运算符 == 相等运算符 对应的表达式:10==3的结果:%d\n", 10 == 3);     // 0
    printf("关系运算符 != 不等运算符 对应的表达式:10!=3的结果:%d\n", 10 != 3);     // 1
  }

  return 0;
}