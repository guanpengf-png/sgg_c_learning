#include <stdio.h>
int main()
{
  // 自增和自减运算符及其表达式的运算过程和结果
  // ++(自增/自加/加加),分为: ++x 前自增/前自加/前加加  或者  x++ 后自增/后自减/后加加
  // --(自减/减减)m,分为 --x 前自减/前减减  或者  x-- 后自减/后减减

  {
    // 后自增:  x++
    // 后自增的运算过程:先取出表达式的值,参与运算,然后再自身加1
    int x = 10;
    int y = x++;
    printf("x=%d,y=%d\n", x, y);
  }
  printf("\n==================\n");
  {
    // 后自减:  x--
    // 后自减的运算过程:先取出表达式的值,参与运算,然后再自身减1
    int x = 10;
    int y = x--;
    printf("x=%d,y=%d\n", x, y);
  }

  printf("\n==================\n");
  {
    // 前自增:  ++x
    // 前自增的运算过程:先取出表达式的值,自身加1,然后再参与运算
    int x = 10;
    int y = ++x;
    printf("x=%d,y=%d\n", x, y);
  }
  printf("\n==================\n");

  {
    // 前自减:  --x
    // 前自减的运算过程:先取出表达式的值,自身减1,然后再参与运算
    int x = 10;
    int y = --x;
    printf("x=%d,y=%d\n", x, y);
  }

  printf("\n==================\n");

  {
    int x = 10;
    int y = ++x + x-- - --x + x++;
    printf("x=%d,y=%d\n",x,y);
  }

  return 0;
}