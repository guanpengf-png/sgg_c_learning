#include <stdio.h>
// 标识符:指的是变量,数组,函数,结构体的名字,就叫标识符
// 强制规范: 只能由字母,数字,或下划线组成,
// 必须使用字母或下划线开头
// 不能以数字开头
// 不能是关键字
// 不能超过长度限制63个
// 严格区分大小写字母,大写和小写是两个不同的名字,name  NAME
// 建议性的规范:
// 标识符的名字尽可能的有意义
// 可以使用下划线的方式连接多个词语
// 如果标识符的名字是一个单词或者是多个单词,尽可能的都使用小写,及其特殊的词语会是大写
// 如果一个标识的名字是多个词语组合,可以使用下划线连接,也可以使用驼峰命名法:
// max_number,所有的词都使用小写
// 驼峰命名法:分为小驼峰命名法和大驼峰命名法
// 小驼峰命名法:指的是多个单词组合,第一个单词小写,后面的单词的首字母大写,如:maxNumber,一般用在变量名,常量名,函数,数组上使用
// 大驼峰命名法:指的是多个单词组合,所有单词的首字母大写,如:MaxNumber,在枚举类型/结构体类型/共用体类型上使用
// 比较好的标识符的命名,是以下划线开头,但是尽量少用, _max_number,少用的原因:容易让其他开发人员误认为当前的标识符可能是系统的

