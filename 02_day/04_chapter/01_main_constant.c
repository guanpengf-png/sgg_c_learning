// 标识符常量:分为使用宏定义#define定义的常量和使用const关键字定义的常量
#include <stdio.h>
int main(){
  // 10; // 字面量,整数字面量,字面量常量,整数字面量常量
  // 12.34;// 字面量,小数字面量/浮点数字面量,字面量常量,小数字/浮点数字面量常量
  // 'A'; // 字面量/字符字面量/字符字面量常量
  // "hello"; // 字面量/字符串字面量/字符串字面量常量
  return 0;
}