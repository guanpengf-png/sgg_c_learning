#include <stdio.h>
// 标识符常量之使用宏定义#define的方式来定义常量
// 语法: #define 宏名 文本
// 语法: #define 常量名 数据
// 注意:宏名/常量名(使用宏定义#define的方式来定义常量) 一般名字都是大写的
// 预处理指令#define定义的常量,会在预处理阶段进行文本替换操作
// 预处理指令#define定义的常量,对应的数据值后面不要加分号
// 需求,通过宏定义的方式来定义标识符常量,计算圆的面积
#define PI 3.14
int main()
{
  // PI = 34.56; 不可以修改的
  // 声明了一个double类型的变量,起名为r,赋值为5.0
  double r = 5.0;
  double s = PI * r * r;
  // %lf---也是格式占位符,用来展示小数的(浮点数的),%.数字lf 表示精确几位小数的含义
  printf("面积是:%.2lf\n", s);

  return 0;
}