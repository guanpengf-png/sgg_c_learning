#include <stdio.h>
int main()
{
  // 指针变量的声明或定义语法:
  // 1. 先声明后赋值的语法: 数据类型 * 指针变量名; 指针变量名 = &变量名/内存地址;
  // 2. 声明的同时直接赋值: 数据类型 * 指针变量名 = &变量名/内存地址;
  // 指针变量的类型(*)前面的类型名应该和指向的变量的类型是一致的
  // 指针的作用(指针变量的作用):多了一种访问或修改数据的方式
  int num = 10;
  // 指针变量的先声明后赋值
  int *ptr1;   // 声明了一个int*类型的指针变量,起名为ptr1
  ptr1 = &num; // & --- 取址符---获取变量的内存地址的
  printf("num变量的值:%d,num变量的内存地址:%p\n", num, &num);
  // %p---格式占位符----输出内存地址
  // *----间接引用符---解引用符----取值符---解引用
  printf("ptr1指针变量指向的内存地址:%p,ptr1指针变量指向的内存地址对应的内存空间中的数据值:%d\n", ptr1, *ptr1);

  double d_num = 12.34;
  // 指针变量的声明的同时直接赋值
  double *ptr2 = &d_num; //  & --- 取址符---获取变量的内存地址的
  printf("d_num变量的值:%lf,d_num变量的内存地址:%p\n", d_num, &d_num);
  printf("ptr2指针变量指向的内存地址:%p,ptr2指针变量指向的内存地址对应的内存空间中的数据值:%lf\n", ptr2, *ptr2);

  // 指针变量声明的时候三种风格
  // int x = 100;
  // int *p1 = &x;
  // int * p2 = &x;
  // int* p3 = &x;

  return 0;
}