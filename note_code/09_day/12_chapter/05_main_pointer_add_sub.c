#include <stdio.h>
int main()
{
  // 1. 指针变量可以加减一个整数,自身指向不变,其结果是向后或向前移动n个单位(n*数据所占的字节数)
  int nums[] = {10, 20, 30, 40, 50};
  for (int i = 0; i < 5; i++)
    printf("索引:%d,元素值:%d,对应的内存地址:%p\n", i, nums[i], &nums[i]);
  // 声明了一个int*类型的指针变量,起名为ptr,指向的是数组中第一个元素的内存地址
  int *ptr = &nums[0];
  printf("ptr指针变量指向的内存地址:%p,对应的数据值:%d\n", ptr, *ptr);
  // 指针变量加整数表示:向后移动多少个单位,也就是向后移动多少个字节
  // 例子: 指针变量+x,表示向后移动x个单位,也可以说向后移动了x*数据类型的字节数
  printf("ptr指针变量加1后指向的内存地址:%p,对应的数据值:%d\n", ptr + 1, *(ptr + 1));
  // 表示指针变量向后移动3个单位(12个字节)
  printf("ptr指针变量加1后指向的内存地址:%p,对应的数据值:%d\n", ptr + 3, *(ptr + 3));
  printf("\n======================\n");
  ptr = &nums[4];
  printf("ptr指针变量指向的内存地址:%p,对应的数据值:%d\n", ptr, *ptr);
  // 向前移动2个单位,也就是8个字节
  printf("ptr指针变量减2后指向的内存地址:%p,对应的数据值:%d\n", ptr - 2, *(ptr - 2));

  return 0;
}