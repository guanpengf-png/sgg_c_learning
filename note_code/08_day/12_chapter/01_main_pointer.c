#include <stdio.h>
int main()
{
  // 内存理解:指的是内存存储空间,由一个一个的内存存储单元组成,每个存储单元都有自己的编号,这个编号就是内存地址
  // 指针:就是指针变量,用来存储变量的内存地址的一个容器
  // 指针就是指针变量,可以用来指向某个变量的内存地址的
  // 指针的作用:多了一种访问/修改数据的方式

  int num = 10; // 声明了一个变量,类型是int,起名为num,并赋值为10
  int *ptr = &num; // 声明了一个指针变量,类型是int *,并赋值为num变量的内存地址
  printf("num变量的数据值是:%d,num变量的内存地址:%p\n",num,&num); // 10 和内存地址
  printf("ptr指针变量指向的内存地址对应的内存空间中的数据值是:%d\n",*ptr); // 10
  printf("ptr指针变量指向的内存地址:%p\n",ptr); // num变量的内存地址
  printf("ptr指针变量自己的内存地址:%p\n",&ptr); // ptr指针变量自己的内存地址
  printf("\n=================\n");
  num += 20; // 直接通过变量的方式修改变量的值
  printf("num变量的数据值是:%d,num变量的内存地址:%p\n",num,&num); // 30 和内存地址
  // 变量的值修改了,指针解引用后的结果也是改变后的结果
  printf("ptr指针变量指向的内存地址对应的内存空间中的数据值是:%d\n",*ptr); // 30
  printf("ptr指针变量指向的内存地址:%p\n",ptr); // num变量的内存地址
  printf("\n=================\n");
  *ptr += 100; // 通过指针的方式修改指向的内存地址对应的内存空间中的数据值(修改变量的值)
  printf("num变量的数据值是:%d,num变量的内存地址:%p\n",num,&num); // 130 和内存地址
  printf("ptr指针变量指向的内存地址对应的内存空间中的数据值是:%d\n",*ptr); // 130
  printf("ptr指针变量指向的内存地址:%p\n",ptr); // num变量的内存地址


  // %p----格式占位符----用来输出内存地址的格式占位符
  // &-----取址符/取地址符号-----简称:--取址符
    // &变量名----该变量的内存地址
  // *-----解引用符/间接引用符----取值符---叫:解引用
    // *指针变量名----解引用----获取的就是指针变量指向的内存地址对应的内存空间中的数据(就是变量的值)


  return 0;
}