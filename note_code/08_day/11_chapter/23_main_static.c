#include <stdio.h>
void func1()
{
  int num1;
  // static int num2 = 20; // 静态局部变量
  static int num2; // 静态局部变量
  printf("num1=%d,num2=%d\n", num1, num2);
  num1++;
  num2++;
  printf("num1=%d,num2=%d\n", num1, num2);
}
void f2()
{
  int num;
  printf("%d\n", num);
}
int main()
{
  func1();
  func1();
  func1();
  func1();
  f2();
  f2();
  f2();
  f2();
  // func1();
  // func1();
  // func1();
  // func1();
  // static是一个关键字,用来修饰变量或者函数和数组和常量
  // 静态变量
  // 静态常量
  // 静态数组
  // 静态函数
  // 如果在一个变量/常量/数组/函数前使用static修饰那么就是静态
  // 局部变量在函数调用结束后会被销毁或释放
  // 静态局部变量,在函数调用之初,开始进行初始化,调用后不会被销毁,再次调用使用的是之前缓存的数据,静态局部变量只有在函数第一次调用的时候只进行一次初始化,并且其生命周期发生变化,局部变量的生命周期是函数每次调用才开始,调用结束后就销毁或释放,在栈中存储
  // 静态局部变量,在函数第一次调用开始,在全局静态区中存储,直到程序结束后才会被释放
  // 静态局部变量声明未赋值,默认值是0,局部变量声明未赋值默认是随机数(垃圾值)

  return 0;
}