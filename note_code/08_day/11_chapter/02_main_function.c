#include <stdio.h>
// 函数的声明或定义
// 函数的功能:计算两个整数的和,参数有两个,都是int类型
// 函数的返回值是int类型
int get_sum(int num1,int num2)
{
  return num1+num2;
}
// 函数的声明或定义
int get_max(int x,int y){
  return x > y ? x : y;
}
int main()
{

  /*
    函数:把一坨重复使用的代码进行包装,在需要的位置进行使用
    函数:把一些重复使用的代码进行封装,在需要的位置进行调用
    函数的使用:应该先定义或声明,然后才能调用
    函数的作用:代码的重用
    为什么需要函数:代码量减少,封装性,维护性增强,可读性,重用性
    函数的理解:就是一个函数就相当于一个功能,每个函数都是独立的
    函数的理解:一个c程序是由一个或多个.c文件组成(.h),一个.c文件由函数组成,函数是程序的最小组成单位
    函数之间可以相互调用(不能直接相互调用,否则就是死循环)
    函数声明或定义的位置:在main主函数的外部,也就是和main函数同级别位置
    函数分类:系统函数(库函数)---系统自带的和自定义函数(自己定义的函数)
    系统函数(库函数--标准库函数)---不需要自己定义,可以直接调用,如:printf/scanf
    自定义函数:需要我们自己定义/声明,然后再调用

    函数定义或声明的语法:
    返回值类型 函数名([参数列表]){
      函数体代码;
    }
    返回值类型:数据类型名,如果一个函数没有返回值则,返回值类型是void
    函数名:就是标识符的名字,符合命名规范,具有对应的含义(名字要有意义)
    函数名:如果是一个单词,一般是所有字母都小写
          如果是多个单词组合,要么使用小驼峰命名法,要么是多个单词都小写,中间使用_连接
    [参数列表]:表示参数可有可无,参数列表指的是可以没有参数,也可以有参数,参数可以是一个也可以是多个
    参数:就是变量的声明
    函数体代码:一行或多行代码,用来实现功能的

    函数的组成:返回值类型,函数名,参数列表,函数体
    



  */

  // 例子:需求:通过函数实现计算两个数字的和
  // 函数中的代码需要在函数调用的时候才会执行
  int x = 10, y = 20;
  int sum = get_sum(x,y);
  printf("和为:%d\n",sum);

  int sum2 = get_sum(100,200);
  printf("和为:%d\n",sum2);
  // 需求:求两个整数中的最大值
  int max_num = get_max(100, 10);
  printf("最大值是:%d\n",max_num);

  return 0;
}