#include <stdio.h>
int main()
{
  // 按位运算的符号:  &---按位与   |-----按位或   ^----按位异或  ~ 按位取反  << 按位左移  >> 按位右移

  // 按位与
  // 口诀:全1为1,否则为0
  // 0000 0111
  // 0000 0010
  // 0000 0010------>2
  printf("& 按位与 运算符 对应的表达式:7&2 的结果是:%d\n", 7 & 2); // 2
  // 按位或
  // 口诀:全0为0,否则为1
  // 0000 0111
  // 0000 0010
  // 0000 0111---->7
  printf("| 按位或 运算符 对应的表达式:7|2 的结果是:%d\n", 7 | 2); // 7
  // 按位异或
  // 口诀:相同为0,否则为1
  // 0000 0111
  // 0000 0010
  // 0000 0101-----5
  printf("^ 按位异或 运算符 对应的表达式:7^2 的结果是:%d\n", 7 ^ 2); // 5
  // 按位左移
  // 0000 0111
  // 0001 1100
  printf("<< 按位左移 运算符 对应的表达式:7<<2 的结果是:%d\n", 7 << 2); // 28
  // 按位右移
  // 0001 1100
  // 0000 0111
  printf(">> 按位右移 运算符 对应的表达式:28>>2 的结果是:%d\n", 28 >> 2); // 7
  // 按位取反,口诀:1变0,0变1
  // 0000 0011
  // 1111 1100 补码
  // 1111 1011 反码
  // 1000 0100 原码
  printf("~ 按位取反 运算符 对应的表达式:~3 的结果是:%d\n", ~3); // -4

  return 0;
}