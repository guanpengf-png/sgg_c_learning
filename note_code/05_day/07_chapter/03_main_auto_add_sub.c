#include <stdio.h>
int main()
{
  // ++(自增/自加/加加) 和 --(自减/减减)
  // ++ 分为前自增(++a)和后自增(a++)
  // 例子:
  // 后自增/后自加/后加加(a++)运算过程:先取出表达式的值参与运算,然后自身加1
  {
    int a = 10;
    int b = a++;
    printf("a=%d,b=%d\n", a, b); // 11 10
  }
  printf("\n==================\n");
  // 例子:
  // 前自增/前自加/前加加(++a)运算过程:先取出表达式的值自身加1,然后再参与运算
  {
    int a = 10;
    int b = ++a;
    printf("a=%d,b=%d\n", a, b);
  }
  printf("\n==================\n");
  // 后自减 (a--)的运算过程:先取出表达式的值参与运算,然后自身减1
  {
    int a = 10;
    int b = a--;
    printf("a=%d,b=%d\n", a, b);
  }
  printf("\n==================\n");
  // 前自减 (--a)的运算过程:先取出表达式的值自身减1,然后参与运算
  {
    int a = 10;
    int b = --a;
    printf("a=%d,b=%d\n", a, b);
  }
  printf("\n===================\n");
  {
    // int x = 10;
    // int y = ++x + x++ - --x - x--;
    // printf("x=%d,y=%d\n", x, y); // 10 0
  }

  return 0;
}