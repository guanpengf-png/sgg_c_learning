#include <stdio.h>
int main()
{
  // 循环体语句之for循环
  /*
    for循环语句

    语法:
    for(表达式1;表达式2;表达式3){
      循环体语句代码;
    }

    for(int i=0;i<3;i++){
      循环体语句代码;
    }


    执行过程:先执行一次表达式1(int i=0)这行代码,然后判断表达式2(i<3)是否成立(真---1---true/假---0---false),如果不成立,则循环结束
    如果成立,则执行循环体语句代码,然后执行表达式3(i++),再次判断表达式2是否成立,一直到不成立,则循环结束

    简化:如果for循环大括号中的代码只有一行,大括号也可以省略,注意缩进
    其实while循环大括号中没有代码,大括号也可以省略

    注意:for循环中的条件表达式,也就是那个充当计数器的变量的使用范围只能在for循环的小括号和大括号中使用


  */
  // 例子: 输出10次,每天吃几个包子
  for (int i = 0; i < 10; i++)
    printf("第%d天吃了%d个包子\n", i + 1, i + 1);
  // printf("最终i的值是:%d\n", i);
  printf("\n=========\n");
  // （2）循环输出数字9~17
  for (int i = 9; i < 18; i++)
    printf("%d\n", i);
  printf("\n=========\n");
  // （3）倒序输出数字56 ~ 43
  for (int i = 56; i >= 43; i--)
    printf("%d\n", i);
  printf("\n=========\n");
  // （4）输出10（包括10）以内所有的偶数
  for (int i = 0; i <= 10; i++)
    if (i % 2 == 0)
      printf("%d\n", i);
  printf("\n=========\n");
  for (int i = 0; i <= 10; i += 2)
    printf("%d\n", i);
  printf("\n=========\n");
  // （5）计算100以内（包括100）所有数字的和
  int sum = 0;
  for (int i = 0; i <= 100; i++)
    sum += i;
  printf("结果是:%d\n", sum);
  printf("\n=========\n");
  // （6）计算10以内所有奇数的乘积
  int ji = 1;
  for (int i = 0; i <= 10; i++)
    if (i % 2 != 0)
      ji *= i;
  printf("结果:%d\n", ji);

  return 0;
}