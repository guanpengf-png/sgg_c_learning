#include <stdio.h>
int main()
{
  // 分支语句之多向分支语句: if-else if相关语句
  /*
    if-else if语句
    语法:
    if(条件表达式1){
      语句1;
    }else if(条件表达式2){
      语句2;
    }else if(条件表达式3){
      语句3;
    }...
    else{
      语句4;
    }


    执行过程: 代码执行到if(条件表达式1)的时候,判断条件表达式1的结果是否为真(真---1--true/假---0---false)
    如果为真,则执行语句1,
    否则,判断条件表达式2是否为真
    如果为真,则执行语句2,
    否则,判断条件表达式3是否为真
    如果为真,则执行语句3,
    ....
    最终如果有else语句,前面条件都不成立,就不执行对应大括号中的代码,最终执行的就是else中的语句4


    简化:如果大括号中只有一行代码,则大括号可以省略,需要注意缩进


  */
  // 例子:输入小甜甜的考试成绩,如果成绩在90(包含)以上则奖励一个包子
  // 如果成绩在80(包含)到90之间,则奖励一个花卷
  // 如果成绩在60(包含)到80之间,则奖励一个馒头
  // 如果成绩在60以下,则奖励个鼓励

  int score = 78; // 成绩
  if (score >= 90)
    printf("奖励一个包子\n");
  else if (score >= 80)
    printf("奖励一个花卷\n");
  else if (score >= 60)
    printf("奖励一个馒头\n");
  else
    printf("你很棒,继续加油");
  printf("程序结束\n");

  return 0;
}