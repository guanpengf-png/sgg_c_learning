#include <stdio.h>
int main()
{
  // 分支语句之双向分支语句:if-else语句
  /*

    if-else语句

    语法:
    if(条件表达式){
      语句1;/代码块1;/代码段1;
    }else{
      语句2;/代码块2;/代码段2;
    }
    条件表达式:该表达式的结果最终是布尔类型
    语句:无论代码是一行还是多行都可以叫语句/代码块/代码段
    执行过程:
    代码执行到if(条件表达式)这一行的时候,要计算表达式的值是否为真(1---真---true/0---假---false)
    如果为真(1/true),则执行大括号中的语句1,执行完毕后继续向后执行
    如果为假(0/false),则执行大括号中的语句2,执行完毕后继续向后执行
    简化写法:如果大括号中的代码只有一行,则大括号可以省略,也需要注意缩进
  */
  // 例子:提示用户输入年龄,成年则提示可以看电影了,否则提示回家写作业
  int age;
  printf("请您输入年龄:\n");
  scanf("%d", &age);
  // 判断
  if (age >= 18)
    printf("可以看电影了,嘿嘿\n");
  else
    printf("回家写作业去,看什么看\n");
  printf("程序结束\n");

 
  return 0;
}