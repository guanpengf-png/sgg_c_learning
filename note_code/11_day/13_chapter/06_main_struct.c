#include <stdio.h>
// 结构体类型也属于自定义数据类型中一种
// 数组:一次性可以存储多个相同类型的数据,是一个容器
// 结构体(结构体类型/结构体变量/结构体成员):一次性可以存储多个不同类型的数据,是一种类型,也是变量(容器)
// 结构体类型的定义:
/*

  语法:
  struct 结构体类型名{
    数据类型 成员名/属性名;
    数据类型 成员名/属性名;
    数据类型 成员名/属性名;
    ...
  };
  换一个表达方式:把多个变量声明放在大括号中
   struct 结构体类型名{
    数据类型 变量名;
    数据类型 变量名;
    数据类型 变量名;
    ...
  };
  结构体类型名:一般使用大驼峰命名法

  结构体类型的定义位置可以在函数外部,有可以在函数内部
*/
// 例子:
// 定义一个学生的结构体类型
struct Student{
  char *name; // 姓名
  char gender; // 性别
  int age; // 年龄
  int math; // 数学成绩
};
// 定义一个老师的结构体类型
struct Teacher{
  char name[20]; // 姓名
  int age; // 年龄
  int english; // 学科
};
