#include <stdio.h>
int main()
{
  // 分支控制语句之单向分支语句:if语句
  /*
    if语句


    语法:
    if(条件表达式){
      语句;/代码块;/代码段;
    }
    条件表达式:该表达式的结果最终是布尔类型
    语句:无论代码是一行还是多行都可以叫语句/代码块/代码段
    执行过程:
    代码执行到if(条件表达式)这一行的时候,会自动的计算条件表达式的结果是否为真.
    如果为真(1---true),则执行大括号中语句代码
    如果为假(0---false),则跳过大括号中的代码向后执行

    简化写法:如果大括号中只有一行代码,大括号是可以省略不写的,但是要注意缩进
  */
  //  例子: 提示用户输入年龄,成年则提示可以看电影了
  int age;
  printf("请您输入年龄:\n");
  scanf("%d", &age);
  if (age >= 18)
  {
    printf("可以看电影了,嘿嘿\n");
  }
  printf("程序结束\n");

  // 简化版
  // int age;
  // printf("请您输入年龄:\n");
  // scanf("%d", &age);
  // if (age >= 18)
  //   printf("可以看电影了,嘿嘿\n");
  // printf("程序结束\n");

  return 0;
}