#include <stdio.h>
int main()
{
  // 关系运算符(比较运算符): == 相等  != 不等 >大于 <小于 >= 大于等于 <=小于等于
  // 关系运算表达式:由关系运算符连接起来的式子
  // 关系运算表达式的结果:是布尔类型(真-----1-----true,假-----0----false)
  int a = 10, b = 5;
  printf("== 相等符号 对应的表达式: a==b 的结果是:%d\n",a==b); // 0
  printf("!= 不等符号 对应的表达式: a!=b 的结果是:%d\n",a!=b); // 1
  printf("> 大于符号 对应的表达式: a>b 的结果是:%d\n",a>b); // 1
  printf(">= 大于等于符号 对应的表达式: a>=b 的结果是:%d\n",a>=b); // 1 
  printf("< 小于符号 对应的表达式: a<b 的结果是:%d\n",a<b); // 0
  printf("<= 小于等于符号 对应的表达式: a<=b 的结果是:%d\n",a<=b); // 0

  return 0;
}