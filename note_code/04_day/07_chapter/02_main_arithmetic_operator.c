#include <stdio.h>
int main()
{
  // 算数运算符: +(正号) -(符号) + - * / % ++ --
  // 算数运算表达式:由算数运算符连接起来的式子

  {
    // +(正号)
    int x = +10;
    int y1 = +x, y2 = -x;
    printf("y1=%d,y2=%d\n", y1, y2);
  }
  printf("\n===============\n");
  {
    // -(负号)
    int x = -10;
    int y1 = -x, y2 = +x;
    printf("y1=%d,y2=%d\n", y1, y2);
  }
  printf("\n===============\n");
  {
    // + - * / %
    int a = 10, b = 3;
    // printf("+ 相加符号 对应的表达式: a+b 的结果是:%d\n",a+b); // 13
    // printf("- 相减符号 对应的表达式: a-b 的结果是:%d\n",a-b); // 7
    // printf("* 相乘符号 对应的表达式: a*b 的结果是:%d\n",a*b); // 30
    // printf("/ 相除符号 对应的表达式: a/b 的结果是:%lf\n",a*1.0/b); // 3
    // printf("%% 求模符号 对应的表达式: a%%b 的结果是:%d\n",a%b); // 1
    printf("%% 求模符号 对应的表达式: a%%b 的结果是:%d\n", 10 % 3);   // 1
    printf("%% 求模符号 对应的表达式: a%%b 的结果是:%d\n", -10 % 3);  // -1
    printf("%% 求模符号 对应的表达式: a%%b 的结果是:%d\n", 10 % -3);  // 1
    printf("%% 求模符号 对应的表达式: a%%b 的结果是:%d\n", -10 % -3); // -1
  }

  return 0;
}