#include <stdio.h>
int main()
{
  // 逻辑运算符: &&--逻辑与(并且)   ||---逻辑或(或者)  !--逻辑非(取非)
  // 逻辑运算表达式:由逻辑运算符连接起来的式子
  // 逻辑运算表达式的结果:布尔类型(真-----1----true/假----0----false)
  // && ----逻辑与的运算过程:表达式1&&表达式2,如果表达式1和表达式2 都成立,则结果为真,只要有一个为假,则整个结果为假
  {
    // &&---逻辑与
    int a = 10, b = 7;
    printf("&& 逻辑与运算符 对应的表达式:a+6<b&&a-2<b 的结果是:%d\n", a + 6 < b && a - 2 > b); // 0
    // 逻辑与短路:如果第一个表达式为假,则后面的表达式不再进行计算
    printf("&& 逻辑与运算符 对应的表达式:a+6<b&&b++>2 的结果是:%d,b=%d\n", a + 6 < b && b++ > 2, b);
  }
  printf("\n====================\n");
  // 逻辑或运算符 ||
  // 逻辑或运算表达式的计算过程: 表达式1||表达式2,如果有一个表达式为真,则整个结果为真,否则为假
  {
    int a = 10, b = 7;
    printf("|| 逻辑或运算符 对应的表达式:a+6<b||a-2>b 的结果是:%d\n", a + 6 < b || a - 2 > b); // 1
    // 逻辑或短路:如果第一个表达式为真,则后面的表达式不再进行计算
    printf("&& 逻辑与运算符 对应的表达式:a+6>b||b++>2 的结果是:%d,b=%d\n", a + 6 > b || b++ > 2, b);
  }
  printf("\n===================\n");
  {
    // 逻辑非----!
    // !表达式的运算过程,真为假,假为真
    int a = 3, b = 5;
    printf("! 逻辑非运算符 对应的表达式: !(a+b>10) 的结果是:%d\n", !(a + b > 10)); // 1
  }

  return 0;
}