#include <stdio.h>
int main()
{
  // 三元运算符:      ?:
  // 三元运算表达式:  由三元运算符连接起来的式子
  // 三元运算表达式语法:  表达式1?表达式2:表达式3
  // 三元运算表达式的运算结果: 要么是表达式2的结果,要么就是表达式3的结果
  // 三元运算表达式的计算过程: 表达式1的运算结果如果为真,则执行表达式2,否则执行表达式3
  // 例子:求两个整数数字中的最大值
  int a = 10, b = 20;
  int max_num = a > b ? a : b;
  printf("最大值:%d\n", max_num);
  // 例子:求三个整数中的最大值
  int x = 20, y = 10, z = 30;
  // 嵌套三元表达式
  int max_num2 = x > y ? (x > z ? x : z) : (y > z ? y : z);
  printf("最大值是:%d\n", max_num2);

  return 0;
}