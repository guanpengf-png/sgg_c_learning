#include <stdio.h>
int num = 100;           // 全局变量
const double PI = 13.14; // 全局常量
char chs[] = "Ahello";   // 全局字符数组
// 全局的变量/全局常量/全局的数组可以在整个的.c文件中访问和使用(任何位置,也可以是其他的函数中)
// 全局变量的数据一旦在程序执行期间,在某个位置进行了修改,后面再访问该数据的时候,就是修改后的数据值

void f1()
{
  // int num = 10;           // 局部变量
  // const double PI = 3.14; // 局部常量
  // char chs[] = "hello";   // 局部字符数组
  // // 局部变量/局部常量/局部数组只能在当前所在的函数中使用
  printf("num=%d\n", num);  // 
  printf("PI=%.2lf\n", PI); // 
  printf("chs=%s\n", chs);  // 
  num += 10;
}

int main()
{
  f1();
  printf("num=%d\n", num);  // 100 
  printf("PI=%.2lf\n", PI); // 13.14
  printf("chs=%s\n", chs);  // Ahello
  return 0;
}

