// 变量:就是一个容器,用来存储或修改数据的
// 变量要想使用,就必须先声明
// 变量的声明有三个要素:数据类型名,变量名,数据值
// 变量的声明的语法: 数据类型名 变量名;
// 变量的声明有三种方式：
// 方式1:先声明后赋值

// 方式2:声明的同时直接赋值

// 方式3:一次性可以声明多个变量

#include <stdio.h>
int main()
{
  // 需求:向内存中存储一个整数10即可

  // 方式1:先声明后赋值
  // 语法:数据类型名 变量名;
  int num1;                            // 声明了一个int类型的变量,起名为num1,
  num1 = 10;                           // 把10这个整数存储都变量num1中
  printf("num1变量的值是:%d\n", num1); // %d----格式占位符,用来输出整数值

  // 方式2:声明的同时直接赋值
  int num2 = 20; // 声明了一个int类型的变量,起名为num2,并存储数字20
  printf("num2变量的值是:%d\n",num2);

  // 一次性可以声明多个变量
  int a = 10, b = 20, c = 30; // 声明了3个int类型的变量,起名为a,b,c,分别赋值10,20,30
  printf("a变量的值是:%d,b变量的值是:%d,c变量的值是:%d\n",a,b,c);
  return 0;
}
