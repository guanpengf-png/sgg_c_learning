#include <stdio.h>
// 标识符常量之#define定义的常量:
// 语法:
// #define 宏名 文本  ---- 宏定义,属于预处理指令
// #define 常量名 数据值
// #define定义常量的时候,结尾不要有分号,名字建议使用大写
// #define宏定义的方式来声明常量,是在预处理阶段进行的文本替换操作(纯文本替换)
// #define声明的常量,是没有类型的,也没有类型检查,也会分配内存空间
// 这种宏定义的方式的位置一般放在主函数(主入口的外部,一般都是在上面位置)
// 这个数据值一旦定义后(存储后),不能再修改的数据值,就会定义常量
#define PI 3.14
int main(){
  // PI = 34.56; // 不可以的
  // 需求:求一个半径为5.0的圆的面积
  double r = 5.0; // 定义一个double类型的变量,起名为r,赋值为5.0
  double s = PI * r * r;
  printf("面积是:%.2lf\n",s);

  // %lf 是格式占位符,用来输出小数的
  // %.数字lf是表示保留小数点后面有几位小数的
  // 如:%.2lf表示小数点后有两位小数
  // double 表示的是浮点数类型(双精度浮点型)
  return 0;
}