#include <stdio.h>
int main()
{
  // 数组:就是一组数据
  // 数组:就是一个容器,可以一次性存储多个相同类型的数据
  // 数组元素:数组中的每个数据值,都可以看成是元素,也可以叫数组元素
  // 数组长度:就是数组中元素的个数(也就是数组中数据的个数)
  // 索引(下标/角标):指的是数组中每个元素的位置标识(编号),从0开始,依次递增加1,到长度减1为止
  // 索引和长度的关系：最大索引加1就是长度,长度减1就是最大索引
  // 索引(下标/角标)的作用:用来获取/设置/修改对应位置数据的
  // 数组越界:指的是通过索引/下标/角标获取的是不在0到最大索引位置的其他位置的数据

  // 数组的不同定义方式的语法:
  // 方式1:先声明数组,后赋值
  // 数据类型 数组名[长度];
  // 赋值语法: 数组名[索引] = 值;
  // 获取数组中某个位置数据的语法: 数组名[索引];
  int nums1[3]; // 声明了一个int[3]类型的数组,起名为nums1
  nums1[0] = 10;
  nums1[1] = 20;
  nums1[2] = 30;
  printf("索引0对应位置的数据是:%d\n", nums1[0]);
  printf("索引1对应位置的数据是:%d\n", nums1[1]);
  printf("索引2对应位置的数据是:%d\n", nums1[2]);
  printf("\n=============\n");
  // 方式2:声明数组的同时直接赋值,并设置长度
  // 语法: 数据类型名 数组名[长度]={元素值1,元素值2,元素值3};
  int nums2[3] = {10, 20, 30}; // 声明了一个int[3]类型的数组,起名为nums2,赋值是10,20,30
  printf("索引0对应位置的数据是:%d\n", nums2[0]);
  printf("索引1对应位置的数据是:%d\n", nums2[1]);
  printf("索引2对应位置的数据是:%d\n", nums2[2]);
  printf("\n=============\n");
  // 方式3:声明数组的同时直接赋值,没有设定长度
  // 语法: 数据类型名 数组名[]={元素值1,元素值2,元素值3,...};
  int nums3[] = {10, 20, 30, 40, 50}; // 声明了int[]类型的数组,起名为nums3,并赋5个值
  printf("索引0对应位置的数据是:%d\n", nums3[0]);
  printf("索引1对应位置的数据是:%d\n", nums3[1]);
  printf("索引2对应位置的数据是:%d\n", nums3[2]);
  printf("索引3对应位置的数据是:%d\n", nums3[3]);
  printf("索引4对应位置的数据是:%d\n", nums3[4]);

  // int num = 10; // 声明了一个int类型的变量,起名为num,赋值为10
  return 0;
}