#include <stdio.h>
int main()
{
  // 字符数组:就是一个数组,里面的元素是字符
  // 字符数组也可以看成是字符串
  // 字符使用一对单引号括起来,字符串使用一对双引号括起来
  // 字符是单个的,字符串是单个的或者是多个的字符组成的
  // 字符数组中需要使用\0标识结束,也就说\0表示字符串的结束
  // 字符数组中的数据可以通过循环遍历的方式进行展示,也可以使用%s格式占位符以字符串的方式输出

  // 字符数组的声明或定义语法:
  // 都可以先声明后赋值,也可以声明的同时直接赋值
  // 数据类型名 数组名[长度]={元素值1,元素值2,元素值3,...};
  // 方式1:声明的同时直接赋值,并设定长度,主动设置\0结尾
  char chs1[5] = {'a', 'b', 'c', 'd', '\0'};
  printf("chs1=%s\n", chs1);
  // 方式2:声明的同时直接赋值,并设定长度,可以省略\0,默认自动增加\0
  char chs2[5] = {'a', 'b', 'c', 'd'};
  printf("chs2=%s\n", chs2);
  // 方式3:声明的同时直接赋值,并设定长度,没有\0的方式(数组已经满了)
  char chs3[5] = {'a', 'b', 'c', 'd', 'e'};
  printf("chs3=%s\n", chs3);
  // 方式4:声明的同时直接赋值,没有设定长度,有\0结尾
  char chs4[] = {'a', 'b', 'c', 'd', '\0'};
  printf("chs4=%s\n", chs4);
  // 方式5:声明的同时直接赋值,没有设定长度,使用双引号的方式赋值,带大括号的
  char chs5[] = {"hello"};
  printf("chs5=%s\n",chs5);
  // 方式6:声明的同时直接赋值,没有设定长度,使用双引号的方式赋值,没有大括号的
  char chs6[] = "hello";
  printf("chs6=%s\n",chs6);
  return 0;
}