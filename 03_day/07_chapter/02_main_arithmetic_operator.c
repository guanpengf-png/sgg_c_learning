#include <stdio.h>
int main()
{
  // 算数运算符: -(负号) +(正号) +(加) -(减) *(乘) /(除) %(取余/求余/取模/求模) ++(自增/自加/加加) --(自减/减减)
  // 算数运算表达式:由算数运算符连接起来的式子
  {
    // +正号
    int x = +10;
    int y1 = -x, y2 = +x;
    printf("y1=%d,y2=%d\n", y1, y2); // -10 10
  }
  printf("\n===================\n");
  {
    // -负号正
    int x = -10;
    int y1 = -x, y2 = +x;
    printf("y1=%d,y2=%d\n", y1, y2); // 10 -10
  }
  printf("\n===================\n");
  {
    // +(加) -(减) *(乘) /(除)
    printf("相加运算符 对应的表达式 10+3 的结果是:%d\n", 10 + 3);        // 13
    printf("相减运算符 对应的表达式 10-3 的结果是:%d\n", 10 - 3);        // 7
    printf("相乘运算符 对应的表达式 10*3 的结果是:%d\n", 10 * 3);        // 30
    printf("相除运算符 对应的表达式 10/3 的结果是:%lf\n", 10 * 1.0 / 3); // 3
  }
  printf("\n===================\n");
  {
    // %(取余)
    // printf("取余运算符 对应的表达式 10%%3 的结果是:%d\n", 10 % 3); //  1
    printf("取余运算符 对应的表达式 10%%3 的结果是:%d\n", 10 % 3);     //  1
    printf("取余运算符 对应的表达式 -10%%3 的结果是:%d\n", -10 % 3);   //  -1
    printf("取余运算符 对应的表达式 10%%-3 的结果是:%d\n", 10 % -3);   //  1
    printf("取余运算符 对应的表达式 -10%%-3 的结果是:%d\n", -10 % -3); // -1
  }

  return 0;
}